"""FraudLens analyst app (Streamlit).

Run it with ``fraudlens-app`` (after ``pip install -e .``), or ``streamlit run streamlit_app.py``.
"""

from __future__ import annotations

import streamlit as st

from fraudlens.app.state import get_world
from fraudlens.app.views import live, performance, simulator, test_payment

GITHUB_URL = "https://github.com/beggumuzun/fraudlens"


def run() -> None:
    st.set_page_config(page_title="FraudLens", page_icon=":material/shield:", layout="wide")

    pages = [
        st.Page(
            live.render,
            title="Live monitor",
            icon=":material/monitoring:",
            url_path="live",
            default=True,
        ),
        st.Page(
            test_payment.render,
            title="Test a payment",
            icon=":material/credit_card:",
            url_path="test-a-payment",
        ),
        st.Page(
            simulator.render,
            title="Attack simulator",
            icon=":material/bug_report:",
            url_path="attack-simulator",
        ),
        st.Page(
            performance.render,
            title="Model performance",
            icon=":material/insights:",
            url_path="model-performance",
        ),
    ]
    page = st.navigation(pages)

    with st.sidebar:
        st.markdown("### FraudLens")
        st.caption(
            "Real-time, explainable card fraud detection. Every payment is scored the moment "
            "it happens, and every alert comes with plain-English reasons."
        )
        st.caption(
            "All customers and payments are synthetic, generated by the project's own data "
            "engine. No real card data is used."
        )
        st.markdown(f"[Source code on GitHub]({GITHUB_URL})")

    get_world()  # build (or fetch the cached) demo world before any page draws
    page.run()


if __name__ == "__main__":
    run()
